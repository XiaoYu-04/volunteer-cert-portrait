-- =============================================================================
-- V1__init_baseline.sql —— 迁移基线（不含任何业务表）
-- =============================================================================
-- 本脚本是 Flyway 迁移链路的起点，故意不包含任何 DDL/DML。
-- 理由：业务表结构尚未设计，此处凭空建表会与后续设计冲突；
--       保留一个空的基线脚本，可让 flyway_schema_history 从 V1 开始记录，
--       后续真实的建表脚本从 V2 起递增即可。
--
-- 命名约定
--   版本化迁移：V{序号}__{描述}.sql（注意是两个下划线）
--     - V 前缀表示 Versioned，执行一次后不再重复执行；
--     - 序号必须递增且不重复，如 V2、V3 …… V10（按数字大小比较，不是字符串）；
--     - 描述用英文小写下划线，如 V2__create_volunteer_table.sql。
--   可重复执行迁移：R__{描述}.sql
--     - R 前缀表示 Repeatable，内容变化时自动重跑，适用于视图、函数、字典数据。
--
-- 使用约定
--   1. 已执行过的脚本不可再修改：Flyway 启动时会比对 checksum，
--      改动历史脚本会导致 validate-on-migrate 失败、应用启动不了。
--      需要变更请新增脚本，而不是改旧的。
--   2. 一个脚本只做一件事（建一张表 / 加一个索引 / 一次数据订正），
--      便于定位问题和按需回滚。
--   3. 脚本必须能在空库上从头按顺序执行通过，不要依赖手工预置的数据或状态。
--   4. 脚本统一使用 UTF-8 编码（对应 spring.flyway.encoding）。
--   5. 执行顺序由版本号决定，与文件在磁盘上的排列无关。
--   6. 不要在脚本里写 CREATE DATABASE / 连接切换语句，迁移在已连接的库上执行。
--
-- 基线说明
--   spring.flyway.baseline-version=0，因此在已有数据的库上自动打基线后，
--   本脚本（V1）仍会被正常执行；执行成功后 flyway_schema_history 中
--   会新增一条 version=1 的成功记录。
-- =============================================================================

-- 本脚本无 DDL/DML 语句，仅作为迁移链路起点与上述约定的载体。