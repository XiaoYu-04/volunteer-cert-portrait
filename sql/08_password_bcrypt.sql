-- =============================================================
-- 高校志愿服务时长认证与公益画像数据分析系统
-- 脚本 8/8：口令明文转 BCrypt 密文（增量，与后端 B15 配套，必需）
-- 数据库类型：PostgreSQL 16+
-- =============================================================
--
-- 为什么需要这个脚本
-- -------------------------------------------------------------
-- 后端 B15 把口令校验从「明文相等比较」换成了 BCrypt 哈希比对
-- （vcp-framework 的 PasswordUtils，强度 10）。改造后 PasswordUtils.matches
-- 遇到库里还是明文的记录一律返回 false —— 这是刻意的，留一条明文兜底等于加密白做。
-- 因此**代码升级前就已建好的库必须执行本脚本，否则所有账号都登录不了**。
--
-- 与 02 / 03 / 04 / 07 的关系
-- -------------------------------------------------------------
-- 03、04、07 三个脚本里的种子口令已同步换成密文，**新库不需要跑本脚本**；
-- 本脚本只服务于「先有库、后有加密代码」的老库。
--
-- 可重复执行
-- -------------------------------------------------------------
-- 只更新口令恰好是明文 123456 的行，已加密的行一行不碰，反复执行无副作用。
--
-- ⚠️ 已知局限：只能处理口令恰好是 123456 的历史数据
-- -------------------------------------------------------------
-- 明文口令不可反推，本脚本依据「演示数据里所有账号的口令都是 123456」这一事实，
-- 直接把这串明文的密文写进去。**若库里存在口令不是 123456 的明文账号，
-- 必须由管理员用「重置密码」接口单独处理**
-- （PUT /api/v1/system/users/{id}/password）。脚本末尾会报出残留数量供核对。
--
-- 执行方式
-- -------------------------------------------------------------
--   psql -U <用户> -h <主机> -p <端口> -d volunteer_cert_portrait -f 08_password_bcrypt.sql
-- =============================================================

SET client_encoding = 'UTF8';

BEGIN;

-- 明文 123456 的 BCrypt 密文：强度 10，由 spring-security-crypto 7.1.1 生成
-- （new BCryptPasswordEncoder(10).encode("123456")，已实测 matches 返回 true）。
-- 同一明文每次哈希结果都不同（盐随机），固定成这一个值只是为了让各人的库完全一致、便于比对。
-- 刻意不加 deleted = 0 过滤：软删除的行也一并刷掉，免得日后恢复数据时又冒出一行明文。
UPDATE sys_user
SET password    = '$2a$10$jPEdxZ8vkTShM79ugE6IZOPtQaMjGq9QqBFhGc9IpzdhIUVywxEwa',
    update_time = CURRENT_TIMESTAMP
WHERE password = '123456';

-- 自检：报出仍然不是 BCrypt 密文的账号数。
-- 只告警不抛异常 —— 抛异常会把上面刚做完的迁移一起回滚，反而更糟。
DO $do$
DECLARE
    plain_cnt BIGINT;
BEGIN
    SELECT COUNT(*) INTO plain_cnt
    FROM sys_user
    WHERE password NOT LIKE '$2%';

    IF plain_cnt = 0 THEN
        RAISE NOTICE '[08] 口令迁移完成：全部账号均为 BCrypt 密文';
    ELSE
        RAISE WARNING '[08] 仍有 % 个账号的口令不是 BCrypt 密文，这些账号登录会失败，请用管理员「重置密码」逐个处理', plain_cnt;
    END IF;
END
$do$;

COMMIT;

-- 核对：正常应为 0 行
SELECT id, username, password
FROM sys_user
WHERE password NOT LIKE '$2%'
ORDER BY id;
